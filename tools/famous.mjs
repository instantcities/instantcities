#!/usr/bin/env node
// Well-known places for the big map's index: the museums, restaurants, schools, churches and the
// rest a city is known for, found by name in the map's OpenStreetMap download.
//
//     node tools/famous.mjs ghent       # ghent/famous.json -> ghent/famous.js
//
// famous.json lists them by kind, each "Name" or "Name|the name OSM gives it". A place OSM has as
// a point (a restaurant) stands there; one it has as an outline (a museum, a school) at the outline's
// middle. A name the download does not have (many museums and schools are mapped on an untagged
// building, or as a point the download left out) is looked up with Nominatim, inside the area's
// bbox, and kept in tools/cache/nominatim-<city>.json. Names found nowhere, or outside the map's
// zone, are left out and listed.
// Map data © OpenStreetMap contributors, available under the ODbL.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mapCoords } from './mapcoords.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const city = process.argv[2];
const DIR = path.join(HERE, '..', city ?? '');
if (!city || !fs.existsSync(path.join(DIR, 'famous.json'))) {
  console.error('usage: node tools/famous.mjs <city>   (the city folder, e.g. ghent, with a famous.json)');
  process.exit(1);
}
const conf = JSON.parse(fs.readFileSync(path.join(DIR, 'famous.json'), 'utf8'));
const { MAP, game, area } = mapCoords(DIR, city);
const osm = JSON.parse(fs.readFileSync(path.join(HERE, 'cache', city + '.json'), 'utf8'));

// Strip accents, case and punctuation, so "S.M.A.K." finds "SMAK" and "Du Progres" "Du Progrès".
const fold = v => v.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

// everything named, by its folded name: [lat, lon, how big] (a point is 0, an outline its node count)
const named = new Map();
const add = (name, lat, lon, size) => {
  const k = fold(name);
  if (!named.has(k) || named.get(k)[2] < size) named.set(k, [lat, lon, size]);
};
for (const n of Object.values(osm.nodes)) if (n.tags?.name) add(n.tags.name, n.lat, n.lon, 0);
for (const w of osm.ways) {
  const name = w.tags?.name;
  if (!name) continue;
  const ps = w.nodes.map(i => osm.nodes[i]).filter(Boolean);
  if (!ps.length) continue;
  add(name, ps.reduce((a, v) => a + v.lat, 0) / ps.length, ps.reduce((a, v) => a + v.lon, 0) / ps.length, ps.length);
}

const inZone = (x, z) => {
  const p = MAP.zone;
  let hit = false;
  for (let i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    if ((p[i + 1] > z) !== (p[j + 1] > z) && x < p[i] + ((z - p[i + 1]) * (p[j] - p[i])) / (p[j + 1] - p[i + 1])) hit = !hit;
  }
  return hit;
};

// Nominatim, at most one request a second as its usage policy asks
const nomFile = path.join(HERE, 'cache', `nominatim-${city}.json`);
const nom = fs.existsSync(nomFile) ? JSON.parse(fs.readFileSync(nomFile, 'utf8')) : {};
async function lookUp(name) {
  if (name in nom) return nom[name];
  await new Promise(r => setTimeout(r, 1100));
  const [s, w, n, e] = area.bbox;
  const url = `https://nominatim.openstreetmap.org/search?format=json&limit=1&bounded=1&viewbox=${w},${n},${e},${s}&q=${encodeURIComponent(name)}`;
  const res = await fetch(url, { headers: { 'User-Agent': 'instant-gent map tool (github.com/woutersmet/instant-gent)' } });
  if (!res.ok) throw new Error(`nominatim ${res.status}`);
  const hit = (await res.json())[0];
  nom[name] = hit ? [Number(hit.lat), Number(hit.lon), 0] : null;
  fs.writeFileSync(nomFile, JSON.stringify(nom, null, 1));
  return nom[name];
}

const out = [], missing = [], seen = new Set();
for (const [kind, list] of Object.entries(conf)) {
  if (kind === '_') continue;
  for (const entry of list) {
    const [name, osmName = name] = entry.split('|');
    if (seen.has(fold(name))) continue;
    const hit = named.get(fold(osmName)) ?? await lookUp(osmName);
    const at = hit && game(hit[0], hit[1]);
    if (!at || !inZone(at[0], at[1])) { missing.push(`${kind}: ${entry}${hit ? ' (outside the zone)' : ''}`); continue; }
    seen.add(fold(name));
    out.push({ name, kind, x: Math.round(at[0]), z: Math.round(at[1]) });
  }
}
fs.writeFileSync(path.join(DIR, 'famous.js'), `// ${city}: generated by tools/famous.mjs from famous.json, do not edit by hand.\n`
  + '// Map data © OpenStreetMap contributors, available under the Open Database License (ODbL).\n'
  + `export const FAMOUS = [\n${out.map(f => '  ' + JSON.stringify(f)).join(',\n')},\n];\n`);
console.error(`${out.length} places${missing.length ? `, not found: ${missing.length}\n  ${missing.join('\n  ')}` : ''}`);
