#!/usr/bin/env node
// Rebuild the game's lookup of existing website pages after editing landmark or site-place data.
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const read = p => JSON.parse(fs.readFileSync(new URL(p, root), 'utf8'));
const pages = {};
const key = s => s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
for (const file of fs.readdirSync(new URL('_data/landmarks/', root))) {
  if (!file.endsWith('.json')) continue;
  const city = file.slice(0, -5), entries = pages[city] = {};
  for (const p of read(`_data/landmarks/${file}`)) {
    const href = `/${city}/landmark/${p.id}/`;
    if (!fs.existsSync(new URL(`.${href}index.html`, root))) throw new Error(`Missing page: ${href}`);
    for (const name of [p.id, p.sight, p.inside, p.name, p.local].filter(Boolean)) entries[key(name)] = href;
  }
}
for (const file of fs.readdirSync(new URL('_data/site_places/', root))) {
  if (!file.endsWith('.json')) continue;
  const city = file.slice(0, -5), entries = pages[city] = {};
  for (const p of read(`_data/site_places/${file}`)) {
    for (const name of [p.id, p.name]) entries[key(name)] = `/sites/${city}/#${p.id}`;
  }
}
// Explicit aliases for cards whose titles differ from their website entries.
const aliases = {
  delft: { 'Markt and Nieuwe Kerk': 'markt', 'Vermeer Centrum': 'vermeer' },
  istanbul: { 'Hippodrome and Blue Mosque': 'hipodrom' },
  'new-york': { 'Grand Central and the Chrysler Building': 'grand-central' },
  pisa: { 'Leaning Tower': 'torre' },
  salerno: { 'Villa Comunale and Teatro Verdi': 'villa-comunale' },
  'taj-mahal': { 'The long canal': 'charbagh', 'The tomb': 'taj-mahal' },
};
for (const [city, names] of Object.entries(aliases)) for (const [name, id] of Object.entries(names)) {
  if (!pages[city][key(id)]) throw new Error(`Missing alias destination: ${city}/${id}`);
  pages[city][key(name)] = pages[city][key(id)];
}
// The hidden game panel belongs to the altarpiece, which has its own artwork page.
pages.ghent[key('rechtvaardige-rechters')] = '/art/ghent-altarpiece/';
pages.ghentinside = pages.ghent;
fs.writeFileSync(new URL('core/js/info-pages.js', root), '// Generated by node tools/info-pages.mjs. Only existing website destinations.\nexport const INFO_PAGES = '+JSON.stringify(pages, null, 2)+';\n');
