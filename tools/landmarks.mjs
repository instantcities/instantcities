#!/usr/bin/env node
// Each city's landmark pages on the site, /<city>/landmark/<id>/, from _data/landmarks/<city>.json
// (_layouts/landmark.html draws them): one little index.html per landmark, saying which it is and,
// for one with a lat and lon inside the city's map, where it lies in the game (x, z), so its page can
// drop you there (/<city>/play/?pos=x,z). Pages of landmarks no longer in the list are removed.
// For a city that has no sight card of its own for such a landmark (no `sight`), it also writes
// <city>/site-sights.js: a card for each, with the landmark's blurb, that shows when you ride up to it
// in the game (core/js/city.js adds them to the city's sights) and leads to its page.
//
//     node tools/landmarks.mjs            # every city with a _data/landmarks/<city>.json
//     node tools/landmarks.mjs venice
//
// A landmark: { id, name, local? (its name in the city's language, where that differs), emoji,
// kind ('place' | 'vehicle' | 'food' | 'tradition' | 'thing'), lat?, lon?, sight? (the id of the
// game's sight card, for ?at=), inside? (a building to walk into, its id in <city>/inside.js: the
// page's link opens the game inside it, also for one off the city's map), image? (a path on the site), blurb (a line or two, on the city's
// page), text (paragraphs), and optionally history (paragraphs), dates ([when, what]) and visit
// (paragraphs) }.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mapCoords } from './mapcoords.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, '_data', 'landmarks');
const cities = process.argv.slice(2).length ? process.argv.slice(2)
  : fs.readdirSync(DATA).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5));

for (const city of cities) {
  const list = JSON.parse(fs.readFileSync(path.join(DATA, city + '.json'), 'utf8'));
  const dir = path.join(ROOT, city), out = path.join(dir, 'landmark');
  const { game, area, MAP } = fs.existsSync(path.join(dir, 'map.js')) ? mapCoords(dir, city) : {};
  // only a landmark inside the map can be ridden to (the Sagrada Família lies outside Barcelona's)
  const onMap = l => area && l.lat != null && l.lon != null && l.lat > area.bbox[0] && l.lat < area.bbox[2] && l.lon > area.bbox[1] && l.lon < area.bbox[3];
  const ids = new Set();
  for (const l of list) {
    if (!/^[a-z0-9-]+$/.test(l.id)) throw new Error(`${city}: landmark id "${l.id}" is not a-z, 0-9 and -`);
    if (ids.has(l.id)) throw new Error(`${city}: landmark id "${l.id}" twice`);
    ids.add(l.id);
    if (l.inside && !fs.readFileSync(path.join(dir, 'inside.js'), 'utf8').includes(`id: '${l.inside}'`)) throw new Error(`${city}: landmark "${l.id}" has no building "${l.inside}" in ${city}/inside.js`);
    const front = ['---', 'layout: landmark', `city: ${city}`, `landmark: ${l.id}`];
    if (onMap(l)) {
      const [x, z] = game(l.lat, l.lon);
      front.push(`x: ${Math.round(x)}`, `z: ${Math.round(z)}`);
    }
    fs.mkdirSync(path.join(out, l.id), { recursive: true });
    fs.writeFileSync(path.join(out, l.id, 'index.html'), front.join('\n') + '\n---\n');
  }
  const cards = list.filter(l => onMap(l) && !l.sight).map(l => {
    const [x, z] = game(l.lat, l.lon);
    return { id: l.id, emoji: l.emoji, x: Math.round(x), z: Math.round(z), r: reach(MAP, x, z), page: `/${city}/landmark/${l.id}/`, text: { en: { name: l.name, text: l.blurb } } };
  });
  const file = path.join(dir, 'site-sights.js');
  if (cards.length) {
    fs.writeFileSync(file, `// ${city}: generated by tools/landmarks.mjs from _data/landmarks/${city}.json, do not edit by hand.\n`
      + '// A sight card for each landmark on the map (see js/city.js), with its page on the site.\n'
      + `export const SITE_SIGHTS = [\n${cards.map(c => `  ${JSON.stringify(c)},`).join('\n')}\n];\n`);
  } else if (fs.existsSync(file)) fs.rmSync(file);
  for (const old of fs.existsSync(out) ? fs.readdirSync(out) : []) {
    if (!ids.has(old)) fs.rmSync(path.join(out, old), { recursive: true });
  }
  console.error(`${city}: ${list.length} landmarks`);
}

// How close you have to come for a landmark's card (game metres): past the walls of the building or
// the edge of the square it stands in, so a big one (the Colosseum) shows from the street around it,
// or 55 m where it stands in neither (a fountain, a column).
function reach(MAP, x, z) {
  let best = 55;
  for (const { p } of [...MAP.buildings, ...MAP.areas.filter(a => a.k !== 'water')]) {
    if (!inside(p, x, z)) continue;
    let far = 0;
    for (let i = 0; i < p.length; i += 2) far = Math.max(far, Math.hypot(p[i] - x, p[i + 1] - z));
    if (far < 250) best = Math.max(best, far + 25); // (not a whole park or quarter)
  }
  return Math.round(Math.min(best, 180));
}

function inside(p, x, z) {
  let c = false;
  for (let i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    if ((p[i + 1] > z) !== (p[j + 1] > z) && x < ((p[j] - p[i]) * (z - p[i + 1])) / (p[j + 1] - p[i + 1]) + p[i]) c = !c;
  }
  return c;
}
