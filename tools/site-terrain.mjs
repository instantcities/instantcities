#!/usr/bin/env node
// A stylised summit/ridge, not a DEM. Keeps the visitor circuits on a level top and lets the
// surrounding ground fall away. node tools/site-terrain.mjs [acropolis machu-picchu]
import fs from 'node:fs';
const ids=process.argv.slice(2);if(!ids.length)ids.push('acropolis','machu-picchu');
for(const id of ids) {
 if(!['acropolis','machu-picchu'].includes(id))throw Error('No terrain profile for '+id);
 const {game}=await import(`../${id}/frame.js`),{MAP}=await import(`../${id}/map.js`);
 const origin=game(0,0),xs=MAP.zone.filter((_,i)=>!(i%2)),zs=MAP.zone.filter((_,i)=>i%2);
 const cell=20,x0=Math.floor((Math.min(...xs)-200)/cell)*cell,z0=Math.floor((Math.min(...zs)-200)/cell)*cell;
 const nx=Math.ceil((Math.max(...xs)+200-x0)/cell),nz=Math.ceil((Math.max(...zs)+200-z0)/cell);
 const buf=Buffer.alloc((nx+1)*(nz+1)*2);
 for(let j=0;j<=nz;j++)for(let i=0;i<=nx;i++) {
  const x=(x0+i*cell-origin[0])/1.25,z=(z0+j*cell-origin[1])/1.25;
  const q=id==='acropolis'?Math.pow(Math.pow(Math.abs((x+35)/210),6)+Math.pow(Math.abs(z/112),6),1/6):Math.pow(Math.pow(Math.abs(x/125),4)+Math.pow(Math.abs(z/270),4),1/4);
  const t=Math.max(0,Math.min(1,(q-.88)/(id==='acropolis'?.52:.9))),smooth=t*t*(3-2*t);
  buf.writeUInt16LE(Math.round(55000*(1-smooth)),(j*(nx+1)+i)*2);
 }
 fs.writeFileSync(`${id}/terrain.js`,`// Generated by tools/site-terrain.mjs. Artistic relief, not surveyed elevations.\nexport const TERRAIN = ${JSON.stringify({x0,z0,cell,nx,nz,mm:buf.toString('base64')})};\n`);
 console.log(`${id}: ${nx} × ${nz} cells, 55 m relief`);
}
